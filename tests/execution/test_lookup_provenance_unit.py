def test_dataset_root_two_level_closure_reaches_all_executions():
    """DS2 <- EXB <- DS1 <- EXA <- DS0: both executions enter the closure,
    each with a consumption arc naming the concrete input rid + version."""
    ml = _FakeML()
    ds0, ds1, ds2 = _ds(1), _ds(2), _ds(3)
    exa, exb = _ex(1), _ex(2)

    ml.add_dataset(ds0, description="raw", producer=None)
    ml.add_dataset(ds1, description="curated", producer=exa)
    ml.add_dataset(ds2, description="trained", producer=exb)
    ml.add_execution(
        exa,
        description="curate",
        workflow=_StubWorkflow(workflow_rid=_wf(1), name="curator"),
        input_datasets=[_StubDataset(ds0, "raw", "0.1.0", consumed_version="0.1.0")],
    )
    ml.add_execution(
        exb,
        description="train",
        workflow=_StubWorkflow(workflow_rid=_wf(2), name="trainer"),
        input_datasets=[_StubDataset(ds1, "curated", "1.0.0", consumed_version="1.0.0")],
    )
    ml.set_versioned_producer(ds1, "1.0.0", exa)

    closure = ml.lookup_provenance(ds2)

    assert isinstance(closure, ProvenanceClosure)
    assert set(closure.executions) == {exa, exb}
    assert closure.executions_visited == 2
    assert closure.traversal_complete is True
    assert closure.cap_hit is False

    # EXB is the root artifact's producer; EXA is in the closure because it
    # produced DS1@1.0.0, which EXB consumed — so the consumption arc lands
    # on EXA (the producer) naming the concrete input and its pinned version.
    assert [a.kind for a in _arcs_of(closure, exb)] == [ArcKind.root]

    exa_consumption = [a for a in _arcs_of(closure, exa) if a.kind == ArcKind.consumption]
    assert len(exa_consumption) == 1
    assert exa_consumption[0].input_rid == ds1
    assert exa_consumption[0].input_version == "1.0.0"
    assert exa_consumption[0].input_type == ArcInputType.dataset
    assert exa_consumption[0].consumed_by == exb
    assert exa_consumption[0].depth == 1

    # DS0 has no producer, so nothing enters the closure through it — but
    # both consumption edges were still observed as dataset facts.
    assert {ds0, ds1} <= set(closure.datasets)


