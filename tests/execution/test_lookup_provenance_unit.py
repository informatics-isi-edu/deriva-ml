def test_unpinned_edge_does_not_consume_dataset_budget():
    """Carried finding (a): an unpinned edge is a quarantine, not an
    expansion — it must not count toward ``datasets_visited`` or eat the
    dataset budget, because nothing was walked."""
    from deriva_ml.core.mixins._provenance_engine import ClosureBuilder, WalkEngine

    builder = ClosureBuilder()
    engine = WalkEngine(None, builder, max_executions=10, dataset_budget=1, closure_mode=True)

    engine.expand_dataset(_ds(1), None, depth=0)
    assert engine.datasets_visited == 0
    assert engine.cap_hit is False

    # A single pinned expansion still fits the budget of 1 — it would not
    # have, had the unpinned edge consumed a slot.
    engine.expand_dataset(_ds(2), "1.0.0", depth=0)
    assert engine.datasets_visited == 1
    assert engine.cap_hit is False


def test_drain_stops_at_cap_and_marks_it():
    """A queue that outlives the execution budget stops the drain and
    reports the traversal as incomplete rather than silently truncating."""
    from deriva_ml.core.mixins._provenance_engine import ClosureBuilder, WalkEngine

    ml = _FakeML()
    exa, exb = _ex(1), _ex(2)
    ml.add_execution(exa, description="a")
    ml.add_execution(exb, description="b")

    builder = ClosureBuilder()
    engine = WalkEngine(ml, builder, max_executions=1, closure_mode=True)
    engine.enqueue_execution(exa, depth=1)
    engine.enqueue_execution(exb, depth=1)
    engine.drain(depth_remaining=None)

    assert engine.executions_visited == 1
    assert engine.cap_hit is True
    assert engine.flags["walked_complete"] is False


