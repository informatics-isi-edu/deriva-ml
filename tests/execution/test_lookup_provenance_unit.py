def test_diamond_two_distinct_consumption_arcs():
    """One shared producer reached through two DIFFERENT inputs yields TWO
    consumption arcs (different input_rid ⇒ different identity)."""
    ml = _FakeML()
    ds_left, ds_right, ds_root = _ds(1), _ds(2), _ds(3)
    shared, consumer = _ex(1), _ex(2)

    ml.add_dataset(ds_left, description="left", producer=shared)
    ml.add_dataset(ds_right, description="right", producer=shared)
    ml.add_dataset(ds_root, description="root", producer=consumer)
    ml.add_execution(shared, description="fan-out producer")
    ml.add_execution(
        consumer,
        description="joins both",
        input_datasets=[
            _StubDataset(ds_left, "left", "1.0.0", consumed_version="1.0.0"),
            _StubDataset(ds_right, "right", "1.0.0", consumed_version="1.0.0"),
        ],
    )
    ml.set_versioned_producer(ds_left, "1.0.0", shared)
    ml.set_versioned_producer(ds_right, "1.0.0", shared)

    closure = ml.lookup_provenance(ds_root)

    consumption = [a for a in _arcs_of(closure, shared) if a.kind == ArcKind.consumption]
    assert len(consumption) == 2
    assert {a.input_rid for a in consumption} == {ds_left, ds_right}


def test_same_identity_rediscovery_dedups_min_depth():
    """The same (kind, consumer, input, version) fact discovered at two
    depths collapses to ONE arc carrying the minimum depth."""
    ml = _FakeML()
    ds_shared, ds_mid, ds_root = _ds(1), _ds(2), _ds(3)
    producer, mid, top = _ex(1), _ex(2), _ex(3)

    ml.add_dataset(ds_shared, description="shared", producer=producer)
    ml.add_dataset(ds_mid, description="mid", producer=mid)
    ml.add_dataset(ds_root, description="root", producer=top)
    ml.add_execution(producer, description="produces shared")
    # `mid` consumes the shared dataset...
    ml.add_execution(mid, description="mid", input_datasets=[_StubDataset(ds_shared, consumed_version="1.0.0")])
    # ...and so does `top`, at a shallower depth, plus it consumes mid's output.
    ml.add_execution(
        top,
        description="top",
        input_datasets=[
            _StubDataset(ds_mid, consumed_version="1.0.0"),
            _StubDataset(ds_shared, consumed_version="1.0.0"),
        ],
    )
    ml.set_versioned_producer(ds_shared, "1.0.0", producer)
    ml.set_versioned_producer(ds_mid, "1.0.0", mid)

    closure = ml.lookup_provenance(ds_root)

    # `producer` was reached from `top` (depth 1) and from `mid` (depth 2),
    # but only the top arc identity repeats per consumer, so assert on the
    # per-consumer arc: exactly one arc per (consumer, input) pair.
    identities = [a.identity() for a in _arcs_of(closure, producer)]
    assert len(identities) == len(set(identities))

    # The shared dataset is consumed by BOTH top and mid — two distinct
    # identities (different consumed_by), each recorded once.
    shared_arcs = [a for a in _arcs_of(closure, producer) if a.input_rid == ds_shared]
    assert {a.consumed_by for a in shared_arcs} == {top, mid}
    # Arc depth is the PRODUCER's hop count from the root: reached from
    # `top` (root, depth 0) the producer sits at depth 1; reached from `mid`
    # (depth 1) it sits at depth 2.
    by_consumer = {a.consumed_by: a for a in shared_arcs}
    assert by_consumer[top].depth == 1
    assert by_consumer[mid].depth == 2


def test_rediscovery_at_shallower_depth_lowers_recorded_depth():
    """A literal re-emission of the SAME arc identity at a shallower depth
    lowers the recorded depth rather than appending a second arc."""
    from deriva_ml.core.mixins._provenance_engine import ClosureBuilder

    builder = ClosureBuilder()
    consumer, producer, ds = _ex(1), _ex(2), _ds(1)
    builder.record_arc(
        producer,
        kind=ArcKind.consumption,
        depth=3,
        consumed_by=consumer,
        input_rid=ds,
        input_type=ArcInputType.dataset,
        input_version="1.0.0",
    )
    builder.record_arc(
        producer,
        kind=ArcKind.consumption,
        depth=1,
        consumed_by=consumer,
        input_rid=ds,
        input_type=ArcInputType.dataset,
        input_version="1.0.0",
    )

    arcs = builder.arcs_for(producer)
    assert len(arcs) == 1
    assert arcs[0].depth == 1


