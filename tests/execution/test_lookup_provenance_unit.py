def _rid(n: int, prefix: str = "1") -> str:
    """Generate a deterministic, catalog-shaped RID.

    Never a human-written literal — every RID in this module comes from
    here, matching the codebase-wide RID discipline.
    """
    return f"{prefix}-{n:04X}"


def _ds(n: int) -> str:
    return _rid(n, prefix="1")


def _ex(n: int) -> str:
    return _rid(n, prefix="2")


def _wf(n: int) -> str:
    return _rid(n, prefix="3")


def _as(n: int) -> str:
    return _rid(n, prefix="4")


def _fv(n: int) -> str:
    return _rid(n, prefix="5")


def _arcs_of(closure: ProvenanceClosure, rid: str):
    return closure.executions[rid].arcs


def _gaps_for(closure: ProvenanceClosure, kind: GapKind, subject: str | None = None):
    return [g for g in closure.gaps if g.kind == kind and (subject is None or g.subject_rid == subject)]


