"""Unit tests for ``DerivaML.lookup_provenance`` (Task 10 — consumption closure).

These reuse the ``_FakeML`` harness from ``test_lookup_lineage_unit`` (its
Task 8 closure seams: snapshot availability, binding scans, and
``ml.calls`` recording) so the closure walk is exercised entirely offline.

Scope pinned here is Task 10's slice of the design
(``docs/superpowers/specs/2026-08-31-lookup-provenance-design.md``):

- root typology + root-version resolution rule (§3),
- ``ArcKind.root`` at depth 0 and ``ArcKind.consumption`` arcs carrying
  concrete inputs (§6.1),
- the assets map with ALL producers and its two gap kinds (§6.2),
- ``no_workflow`` / ``unresolved_rid`` / ``sentinel_origin`` gaps,
- the unpinned-input quarantine (gap + provably zero snapshot-dependent
  seam calls),
- arc-identity dedup with minimum depth, and the strict execution budget,
- the version-authorship leg (§6.3) and the member-binding leg (§6.4).

``Dataset_Dataset`` containment is NOT a closure arc (ruling 8, #389):
provenance is execution-mediated, so a parent dataset enters only through
the consumption arc of the execution that authored the child version.
``test_containment_parents_are_not_walked`` and
``test_split_parent_enters_through_the_split_executions_consumption_arc``
pin the negative and positive halves of that rule.

Every RID is generated by ``_rid`` — never a hand-written literal (the
repo-wide RID discipline).
"""

