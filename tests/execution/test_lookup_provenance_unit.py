def _authorship_arcs(closure: ProvenanceClosure, rid: str):
    return [a for a in _arcs_of(closure, rid) if a.kind == ArcKind.version_authorship]


def _snapshot_row(dataset_rid: str, version: str, execution: str | None, rct: str) -> dict:
    """Build one snapshot-scoped ``Dataset_Version`` row.

    Shaped exactly like ``_dataset_version_rows``' output so the snapshot
    read and the live read are interchangeable to the engine.
    """
    return {
        "RID": f"{dataset_rid}-VER-{version}",
        "RCT": rct,
        "Version": version,
        "Execution": execution,
        "Description": None,
    }


def _dataset_root_with_snapshot_authors(
    ml: _FakeML,
    dataset_rid: str,
    walked_version: str,
    rows: list[dict],
    *,
    live_rows: list[dict] | None = None,
) -> None:
    """Script a Dataset root pinned at ``walked_version`` whose snapshot read
    returns ``rows``.

    ``live_rows`` (defaulting to ``rows``) feeds the LIVE
    ``_dataset_version_rows`` seam, which the root-version resolution uses;
    the authorship leg must read ``rows`` instead.
    """
    ml.add_dataset(dataset_rid, description="root", producer=None)
    for row in live_rows if live_rows is not None else rows:
        ml.add_version_row(dataset_rid, row["Version"], row["Execution"], rct=row["RCT"])
    ml.set_snapshot_available(dataset_rid, walked_version, True)
    ml.set_snapshot_version_rows(dataset_rid, walked_version, rows)


def test_authorship_bounded_at_walked_version():
    """Walked at 0.2.0 with snapshot rows 0.1.0/0.2.0/0.3.0: the authors of
    0.1.0 and 0.2.0 enter the closure with version_authorship arcs; 0.3.0's
    author does not (a later version's author must never leak into a pinned
    closure)."""
    ml = _FakeML()
    ds = _ds(1)
    author_1, author_2, author_3 = _ex(1), _ex(2), _ex(3)
    for ex in (author_1, author_2, author_3):
        ml.add_execution(ex, description=f"authored by {ex}")

    rows = [
        _snapshot_row(ds, "0.1.0", author_1, "2025-01-01T00:00:00Z"),
        _snapshot_row(ds, "0.2.0", author_2, "2025-02-01T00:00:00Z"),
        _snapshot_row(ds, "0.3.0", author_3, "2025-03-01T00:00:00Z"),
    ]
    _dataset_root_with_snapshot_authors(ml, ds, "0.2.0", rows)

    closure = ml.lookup_provenance(ds, version="0.2.0")

    assert {author_1, author_2} <= set(closure.executions)
    assert author_3 not in closure.executions

    for author, version in ((author_1, "0.1.0"), (author_2, "0.2.0")):
        arcs = _authorship_arcs(closure, author)
        assert len(arcs) == 1
        assert arcs[0].input_rid == ds
        assert arcs[0].input_version == version
        assert arcs[0].input_type == ArcInputType.dataset

    # And the facts carry exactly the bounded attribution trace.
    facts = closure.datasets[ds].versions["0.2.0"]
    assert [va.version for va in facts.version_authors] == ["0.1.0", "0.2.0"]
    assert [va.execution_rid for va in facts.version_authors] == [author_1, author_2]


