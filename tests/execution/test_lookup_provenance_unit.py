def test_feature_value_root_closure():
    """A feature value's closure is its binding execution + that execution's
    own upstream closure."""
    ml = _FakeML()
    fv, binder, upstream = _fv(1), _ex(1), _ex(2)
    ds0 = _ds(1)

    ml.add_dataset(ds0, description="raw", producer=upstream)
    ml.add_execution(upstream, description="ingest", workflow=_StubWorkflow(workflow_rid=_wf(2), name="ingest"))
    ml.add_execution(
        binder,
        description="annotate",
        workflow=_StubWorkflow(workflow_rid=_wf(1), name="annotator"),
        input_datasets=[_StubDataset(ds0, "raw", "0.1.0", consumed_version="0.1.0")],
    )
    ml.add_feature_value(fv, producer_execution=binder)
    ml.set_versioned_producer(ds0, "0.1.0", upstream)

    closure = ml.lookup_provenance(fv)

    assert closure.root.type == "Feature"
    assert set(closure.executions) == {binder, upstream}
    assert any(a.kind == ArcKind.root and a.depth == 0 for a in _arcs_of(closure, binder))


