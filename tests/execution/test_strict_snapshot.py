"""Unit tests for ``Dataset.strict_version_snapshot_catalog`` (#383 Task 7).

``_version_snapshot_catalog`` (the existing, non-strict resolver) falls back
to a **bare-catalog-id** (i.e. live) snapshot handle when a version row's
``Snapshot`` column is empty — verified fact, not a re-derivation: see
``dataset.py:_version_snapshot_catalog_id``, which returns
``self._ml_instance.catalog.catalog_id`` (no ``"@snapshot"`` suffix) on that
path, and ``_version_snapshot_catalog`` still calls ``catalog_snapshot(...)``
with that bare id rather than returning ``self._ml_instance`` directly (the
direct-return path is only for a falsy *input* version).

That live fallback is unacceptable for provenance semantics: a pinned
closure must never let post-snaptime state leak in through a silent live
read. ``strict_version_snapshot_catalog`` is the snapshot-closed sibling
that raises ``SnapshotUnavailable`` instead of ever calling
``catalog_snapshot`` with a bare id. It gates the closure's
version-authorship and member-binding legs.

(The ``strict_parents_at`` sibling this file used to cover was removed with
the ancestry leg — ruling 8, #389: containment is structure, not
provenance.)

Offline: no live catalog. ``Dataset.__init__`` is ``@validate_call``-guarded
against the ``DerivaMLCatalog`` runtime-checkable Protocol, so plain
``MagicMock()`` catalogs (as used freely in
``tests/dataset/test_get_dataset_minid_helpers.py``, which mocks the
``Dataset`` object itself, not the catalog it wraps) fail pydantic's
``isinstance`` check. ``MagicMock(spec=DerivaMLCatalog)`` satisfies it — the
pattern used throughout this file. RIDs are generated by ``_rid()`` — never
hand-written literals.
"""

from __future__ import annotations

from unittest.mock import MagicMock

import pytest

from deriva_ml.core.exceptions import DerivaMLException, SnapshotUnavailable
from deriva_ml.dataset.aux_classes import DatasetHistory, DatasetVersion
from deriva_ml.dataset.dataset import Dataset
from deriva_ml.interfaces import DerivaMLCatalog


def _rid(n: int, prefix: str = "1") -> str:
    """Deterministic, catalog-shaped RID — never a human-written literal."""
    return f"{prefix}-{n:04X}"


def _history_row(version: str, snapshot: str | None, *, dataset_rid: str, version_rid_n: int) -> DatasetHistory:
    return DatasetHistory(
        dataset_version=DatasetVersion.parse(version),
        dataset_rid=dataset_rid,
        version_rid=_rid(version_rid_n),
        snapshot=snapshot,
    )


def _fake_catalog(catalog_id: str = "1", ml_schema: str = "deriva-ml") -> MagicMock:
    """A ``MagicMock(spec=DerivaMLCatalog)`` with a settable ``catalog.catalog_id``.

    ``spec=DerivaMLCatalog`` is what makes this pass ``Dataset.__init__``'s
    pydantic ``isinstance`` check (see module docstring) — a bare
    ``MagicMock()`` does not, because ``DerivaMLCatalog`` is a
    ``@runtime_checkable`` Protocol and pydantic's ``is_instance_of``
    validator requires every protocol attribute to actually be present.
    """
    catalog = MagicMock(spec=DerivaMLCatalog)
    catalog.ml_schema = ml_schema
    catalog.catalog = MagicMock()
    catalog.catalog.catalog_id = catalog_id
    return catalog


